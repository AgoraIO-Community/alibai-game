import { writeFile } from 'node:fs/promises';
import { fixtures } from '../../lib/scenarios/fixtures';
import { assertValid } from '../../lib/scenarios/validate';
async function main() {
  const lines = ['-- Generated by pnpm scenarios:seed-sql. Handcrafted, validated immutable cases.', 'begin;'];
  for (const fixture of fixtures) {
   const scenario = assertValid(fixture);
   const json = JSON.stringify(scenario).replaceAll("'", "''");
   lines.push(`select public.publish_scenario('${json}'::jsonb) where not exists(select 1 from public.scenarios where fingerprint='${scenario.fingerprint}');`);
  }
  lines.push('commit;');
  await writeFile('supabase/seed.sql', `${lines.join('\n')}\n`);
  console.log(`Wrote ${fixtures.length} validated scenarios to supabase/seed.sql`);
}
main().catch(error => { console.error(error instanceof Error ? error.message : 'Unknown CLI error'); process.exitCode = 1; });
